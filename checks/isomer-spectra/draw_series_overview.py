    card(s,345,20,510,126,'SLR-цепочка',['Ядра, швы и упорядоченная конечная пара'])
    for start,end in [((400,146),(185,230)),((600,146),(600,230))]:s.arrow(start,end)
    card(s,20,240,330,165,'Матроидные данные',
         ['Обычные леса, остовное','число и резистивный радиус','Общие при фиксированном N'])
