"""Conceptual map for the series navigator; no mathematical data are generated."""
from draw_three_hexagons import SVG, INK, MUTED, BLUE, GREEN, RED


def card(s,x,y,w,h,title,lines,color=BLUE):
    s.panel(x,y,w,h)
    s.line((x+20,y+20),(x+w-20,y+20),color,4)
    s.text(x+w/2,y+57,title,20 if w<=330 and len(title)>24 else 23,color,'middle','bold')
    for i,line in enumerate(lines):
        s.text(x+w/2,y+94+29*i,line,20,INK,'middle')


